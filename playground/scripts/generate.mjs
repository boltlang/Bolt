// Write the text files the component needs as modules in src/vendor/, so
// that apps that use it don't have to serve them: the highlighting queries
// of the grammar, and the files of the package `std`.
//
//   node scripts/generate.mjs <grammar queries dir> <std dir> <out dir>

import fs from "node:fs";
import path from "node:path";

const [queries, std, out] = process.argv.slice(2);
if (!queries || !std || !out) throw new Error("usage: generate.mjs <queries> <std> <out>");

const header = "// Generated by scripts/generate.mjs. Don't edit it: run `npm run build`.\n\n";
const read = (file) => fs.readFileSync(file, "utf8");

fs.writeFileSync(
  path.join(out, "queries.ts"),
  header +
    `export const highlights: string = ${JSON.stringify(read(path.join(queries, "highlights.scm")))};\n` +
    `export const injections: string = ${JSON.stringify(read(path.join(queries, "injections.scm")))};\n`,
);

const files = fs
  .readdirSync(std, { recursive: true })
  .map((file) => file.split(path.sep).join("/"))
  .filter((file) => file.endsWith(".bolt"))
  .sort();
const entries = files.map((file) => `  ${JSON.stringify(file)}: ${JSON.stringify(read(path.join(std, file)))},`);
fs.writeFileSync(
  path.join(out, "std.ts"),
  header +
    "/** The files of the package `std`, by their path in it, like `__prelude__/lib.bolt`. */\n" +
    `export const stdFiles: Record<string, string> = {\n${entries.join("\n")}\n};\n`,
);
